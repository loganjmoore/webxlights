export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
export const GLYPH_ADVANCE = GLYPH_WIDTH + 1; // one blank column between characters

const UNKNOWN: number[] = [0x7f, 0x41, 0x41, 0x41, 0x7f]; // hollow box for unmapped characters

export function glyphColumns(ch: string): number[] {
  return GLYPHS[ch] ?? UNKNOWN;
}

// True if the glyph for `ch` paints at (col, row), row 0 being the glyph's top row.
export function glyphPixel(ch: string, col: number, row: number): boolean {
  if (col < 0 || col >= GLYPH_WIDTH || row < 0 || row >= GLYPH_HEIGHT) return false;
  return (glyphColumns(ch)[col]! & (1 << row)) !== 0;
}

export function measureText(text: string): { width: number; height: number } {
  if (text.length === 0) return { width: 0, height: GLYPH_HEIGHT };
  return { width: text.length * GLYPH_ADVANCE - 1, height: GLYPH_HEIGHT };
}
