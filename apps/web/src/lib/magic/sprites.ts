import type { PictureImage, PictureMovement } from "@webxlights/engine";

// The picture library: small cartoon sprites for the matrix, drawn here as text, one character
// a pixel. Pixel art rather than generated images: it reads on a 32-64 pixel matrix, its frames
// line up exactly (a loop that shifts a pixel between frames looks like a jitter on a matrix),
// it costs nothing, and every one is an original drawing. "." is off (black).
//
// A lyric word that names one of these (sprites.words) puts it on the matrix while it is sung
// (docs/MAGIC-SEQUENCE.md, "Pictures from the lyrics").

export interface Sprite {
  id: string;
  label: string;
  /** Lyric words that call it up, lower case. */
  words: string[];
  /** How it moves across the matrix while it plays. */
  movement: PictureMovement;
  fps: number;
  /** Colour per character beyond the shared ones. */
  colours?: Record<string, string>;
  /** Rows of characters, top first, every frame the same size. */
  frames: string[];
}

