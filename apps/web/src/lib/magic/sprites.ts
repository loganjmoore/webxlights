const byId = new Map(SPRITES.map((s) => [s.id, s]));
const decoded = new Map<string, PictureImage[]>();

function hexRgb(hex: string): [number, number, number] {
  return [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)) as [number, number, number];
}

/** A sprite's frames as images the Pictures effect draws, decoded once. */
export function spriteFrames(id: string): PictureImage[] | undefined {
  const cached = decoded.get(id);
  if (cached) return cached;
  const sprite = byId.get(id);
  if (!sprite) return undefined;
  const colours = { ...SHARED, ...sprite.colours };
  const frames = sprite.frames.map((frame) => {
    const rows = frame.split("\n");
    const width = Math.max(...rows.map((r) => r.length)), height = rows.length;
    const data: number[] = [];
    for (const row of rows) {
      for (let x = 0; x < width; x++) {
        const c = colours[row[x] ?? "."];
        data.push(...(c ? [...hexRgb(c), 255] : [0, 0, 0, 0]));
      }
    }
    return { width, height, data };
  });
  decoded.set(id, frames);
  return frames;
}

export function spriteById(id: string): Sprite | undefined {
  return byId.get(id);
}

const byWord = new Map(SPRITES.flatMap((s) => s.words.map((w) => [w, s] as const)));

/**
 * The sprite a sung line calls up: its first word the library knows ("boots", "sleigh"), read
 * plainly and without a plural or possessive "s" ("reindeers", "Santa's").
 */
export function spriteFor(line: string): Sprite | undefined {
  for (const raw of line.toLowerCase().split(/[^a-z']+/)) {
    const word = raw.replace(/'s$|'$/, "");
    const sprite = byWord.get(word) ?? (word.endsWith("s") ? byWord.get(word.slice(0, -1)) : undefined);
    if (sprite) return sprite;
  }
  return undefined;
}
